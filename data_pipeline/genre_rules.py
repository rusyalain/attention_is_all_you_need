def exclusion_reason(row):
    author=row['author_key'];title=norm(row['title'])
    if title in EXCLUDE.get(author,set()):
        return 'genre_qa_nonfiction_poetry_play_or_mixed_collection'
    if author in ALLOW and title not in ALLOW[author]:
        return 'conservative_fiction_selection_from_broad_prose_category'
